#!/usr/bin/env python3
"""Generate python/ai-engine/requirements.txt from the vendored nanobot pyproject.toml.

Reads the upstream pyproject.toml and emits the base runtime dependencies plus
the ``api`` extra (aiohttp), which is required by ``nanobot serve``.

Usage:
    python3 scripts/generate-requirements.py [--write]
"""
from __future__ import annotations

import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENGINE_DIR = HERE.parent  # python/ai-engine
PYPROJECT = ENGINE_DIR / "pyproject.toml"
REQUIREMENTS = ENGINE_DIR / "requirements.txt"

HEADER = (
    "# Auto-generated by scripts/generate-requirements.py from pyproject.toml "
    "(nanobot-ai 0.3.0, vendored).\n"
    "# Do not edit by hand; edit pyproject.toml and re-run the generator.\n"
)


def main() -> int:
    with PYPROJECT.open("rb") as f:
        data = tomllib.load(f)

    project = data.get("project", {})
    base = project.get("dependencies", [])
    extras = project.get("optional-dependencies", {})
    api_extra = extras.get("api", [])

    seen: list[str] = []
    for raw in [*base, *api_extra]:
        if raw not in seen:
            seen.append(raw)

    lines = [HEADER, *seen, ""]
    text = "\n".join(lines)

    if "--write" in sys.argv:
        REQUIREMENTS.write_text(text, encoding="utf-8")
        print(f"wrote {REQUIREMENTS.relative_to(ENGINE_DIR.parent.parent)} ({len(seen)} requirements)")
        return 0

    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
